package main

import (
	"flag"
	"fmt"
	"pdbgen/readxml"
	"strings"
)

func main() {
	schemaFile := flag.String(
		"schema",
		"./pdb.xml",
		"schema xml file",
	)

	outDir := flag.String(
		"out",
		"ptable",
		"ddl output directory, default: genOutput in xml",
	)

	flag.Parse()

	schema, err := readxml.LoadSchema(*schemaFile)
	if err != nil {
		panic(err)
	}

	if *outDir == "" {
		*outDir = schema.GenOutput
	}

	if *outDir == "" {
		*outDir = "./ddl/generated"
	}

	if err := generate(schema, *outDir); err != nil {
		panic(err)
	}
}

