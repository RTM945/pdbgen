package main

import (
	"context"
	"flag"
	"fmt"
	"pdbgen/readxml"
	"strings"
	"time"

	"github.com/jackc/pgx/v5"
)

type DBTable struct {
	Name       string
	Columns    map[string]DBColumn
	Indexes    map[string]DBIndex
	PrimaryKey *DBPrimaryKey
}

type DBColumn struct {
	Name       string
	DataType   string
	IsNullable bool
	IsIdentity bool
}

type DBPrimaryKey struct {
	Name    string
	Columns []string
}

type DBIndex struct {
	Name    string
	Unique  bool
	Columns []string
	Where   string // 部分索引的条件，pg_get_expr 反解出来的；普通索引为空
}

func main() {
	schemaFile := flag.String(
		"schema",
		"./pdb.xml",
		"schema xml file",
	)

	flag.Parse()

	schema, err := readxml.LoadSchema(*schemaFile)
	if err != nil {
		panic(err)
	}

	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()

	conn, err := pgx.Connect(ctx, schema.URL)
	if err != nil {
		panic(err)
	}
	defer conn.Close(ctx)

	if err := generate(ctx, schema, conn); err != nil {
		panic(err)
	}
}

func generate(ctx context.Context, schema *readxml.Schema, conn *pgx.Conn) error {
	dbTables, err := inspectDatabase(ctx, conn, schema.Schema)
	if err != nil {
		return err
	}

	var b strings.Builder

	b.WriteString("-- Code generated by pdb ddl generator; DO NOT EDIT.\n\n")

	// schema 不存在时创建
	fmt.Fprintf(
		&b,
		"CREATE SCHEMA IF NOT EXISTS %s;\n\n",
		quoteIdent(schema.Schema),
	)

	for _, table := range schema.Tables {
		dbTable, exists := dbTables[table.Name]

		b.WriteString(
			fmt.Sprintf(
				"-- ============================================================\n"+
					"-- TABLE: %s.%s\n"+
					"-- ============================================================\n\n",
				schema.Schema,
				table.Name,
			),
		)

		if !exists {
			if err := generateMissingTableDDL(&b, schema, table); err != nil {
				return err
			}

			b.WriteString("\n")
			continue
		}

		if err := generateAlterDDL(&b, schema, table, dbTable); err != nil {
			return err
		}

		b.WriteString("\n\n")
	}
	fmt.Println(b.String())

	return nil
}

func inspectDatabase(ctx context.Context, conn *pgx.Conn, schemaName string) (map[string]*DBTable, error) {
	result := make(map[string]*DBTable)

	rows, err := conn.Query(
		ctx,
		`
SELECT table_name
FROM information_schema.tables
WHERE table_schema = $1
  AND table_type = 'BASE TABLE'
ORDER BY table_name
`,
		schemaName,
	)
	if err != nil {
		return nil, err
	}

	for rows.Next() {
		var tableName string

		if err := rows.Scan(&tableName); err != nil {
			rows.Close()
			return nil, err
		}

		result[tableName] = &DBTable{
			Name:    tableName,
			Columns: make(map[string]DBColumn),
			Indexes: make(map[string]DBIndex),
		}
	}

	if err := rows.Err(); err != nil {
		rows.Close()
		return nil, err
	}

	rows.Close()

	// columns
	rows, err = conn.Query(
		ctx,
		`
SELECT
	table_name,
	column_name,
	data_type,
	is_nullable,
	is_identity
FROM information_schema.columns
WHERE table_schema = $1
ORDER BY table_name, ordinal_position
`,
		schemaName,
	)
	if err != nil {
		return nil, err
	}

	for rows.Next() {
		var (
			tableName  string
			columnName string
			dataType   string
			nullable   string
			identity   string
		)

		if err := rows.Scan(
			&tableName,
			&columnName,
			&dataType,
			&nullable,
			&identity,
		); err != nil {
			rows.Close()
			return nil, err
		}

		table, ok := result[tableName]
		if !ok {
			continue
		}

		table.Columns[columnName] = DBColumn{
			Name:       columnName,
			DataType:   normalizeDBType(dataType),
			IsNullable: nullable == "YES",
			IsIdentity: identity == "YES",
		}
	}

	if err := rows.Err(); err != nil {
		rows.Close()
		return nil, err
	}

	rows.Close()

	// primary keys
	rows, err = conn.Query(
		ctx,
		`
SELECT
	t.relname AS table_name,
	c.conname,
	array_agg(a.attname ORDER BY k.ord)
FROM pg_constraint c
JOIN pg_class t
	ON t.oid = c.conrelid
JOIN pg_namespace n
	ON n.oid = t.relnamespace
JOIN LATERAL unnest(c.conkey)
	WITH ORDINALITY AS k(attnum, ord)
	ON true
JOIN pg_attribute a
	ON a.attrelid = t.oid
	AND a.attnum = k.attnum
WHERE n.nspname = $1
  AND c.contype = 'p'
GROUP BY t.relname, c.conname
`,
		schemaName,
	)
	if err != nil {
		return nil, err
	}

	for rows.Next() {
		var (
			tableName string
			name      string
			columns   []string
		)

		if err := rows.Scan(
			&tableName,
			&name,
			&columns,
		); err != nil {
			rows.Close()
			return nil, err
		}

		if table, ok := result[tableName]; ok {
			table.PrimaryKey = &DBPrimaryKey{
				Name:    name,
				Columns: columns,
			}
		}
	}

	if err := rows.Err(); err != nil {
		rows.Close()
		return nil, err
	}

	rows.Close()

	// indexes
	rows, err = conn.Query(
		ctx,
		`
SELECT
	t.relname AS table_name,
	i.relname AS index_name,
	x.indisunique,
	array_agg(a.attname ORDER BY k.ord),
	COALESCE(pg_get_expr(x.indpred, x.indrelid), '')
FROM pg_class t
JOIN pg_namespace n
	ON n.oid = t.relnamespace
JOIN pg_index x
	ON x.indrelid = t.oid
JOIN pg_class i
	ON i.oid = x.indexrelid
JOIN LATERAL unnest(x.indkey)
	WITH ORDINALITY AS k(attnum, ord)
	ON true
LEFT JOIN pg_attribute a
	ON a.attrelid = t.oid
	AND a.attnum = k.attnum
WHERE n.nspname = $1
  AND t.relkind IN ('r', 'p')
  AND i.relkind = 'i'
GROUP BY
	t.relname,
	i.relname,
	x.indisunique,
	COALESCE(pg_get_expr(x.indpred, x.indrelid), '')
`,
		schemaName,
	)
	if err != nil {
		return nil, err
	}

	for rows.Next() {
		var (
			tableName string
			indexName string
			unique    bool
			columns   []string
			where     string
		)

		if err := rows.Scan(
			&tableName,
			&indexName,
			&unique,
			&columns,
			&where,
		); err != nil {
			rows.Close()
			return nil, err
		}

		table, ok := result[tableName]
		if !ok {
			continue
		}

		table.Indexes[indexName] = DBIndex{
			Name:    indexName,
			Unique:  unique,
			Columns: columns,
			Where:   where,
		}
	}

	if err := rows.Err(); err != nil {
		rows.Close()
		return nil, err
	}

	rows.Close()

	return result, nil
}

func generateMissingTableDDL(b *strings.Builder, schema *readxml.Schema, table readxml.Table) error {
	bean, err := readxml.FindBean(schema, table.Bean)
	if err != nil {
		return err
	}

	// CREATE TABLE
	fmt.Fprintf(
		b,
		"CREATE TABLE IF NOT EXISTS %s.%s (\n",
		quoteIdent(schema.Schema),
		quoteIdent(table.Name),
	)

	for i, v := range bean.Variables {
		columnType, defaultValue, err := sqlType(v.Type)
		if err != nil {
			return fmt.Errorf("table %s column %s: %w", table.Name, v.Name, err)
		}
		if table.PrimaryKey != nil &&
			v.Name == table.PrimaryKey.Variable &&
			table.PrimaryKey.AutoIncrement {
			// 自增主键由 IDENTITY 负责生成，不设置 DEFAULT
			fmt.Fprintf(
				b,
				"\t%s %s NOT NULL",
				quoteIdent(readxml.SnakeCase(v.Name)),
				columnType,
			)
		} else {
			fmt.Fprintf(
				b,
				"\t%s %s NOT NULL DEFAULT %s",
				quoteIdent(readxml.SnakeCase(v.Name)),
				columnType,
				defaultValue,
			)
		}

		if i != len(bean.Variables)-1 {
			b.WriteString(",")
		}

		b.WriteString("\n")
	}

	b.WriteString(");\n\n")

	// PRIMARY KEY / IDENTITY
	if table.PrimaryKey != nil {
		if err := generatePrimaryKeyDDL(b, schema, table); err != nil {
			return err
		}
	}

	// INDEX
	for _, index := range table.Indexes {
		if err := generateIndexDDL(b, schema, table, index); err != nil {
			return err
		}

		b.WriteString("\n")
	}

	return nil
}

func generatePrimaryKeyDDL(
	b *strings.Builder,
	schema *readxml.Schema,
	table readxml.Table,
) error {
	pk := table.PrimaryKey

	var actions []string

	if pk.AutoIncrement {
		identity := fmt.Sprintf(
			"ALTER COLUMN %s ADD GENERATED ALWAYS AS IDENTITY",
			quoteIdent(readxml.SnakeCase(pk.Variable)),
		)

		options, err := identityOptions(pk.Start, pk.Step)
		if err != nil {
			return fmt.Errorf("table %s primary key: %w", table.Name, err)
		}
		identity += options

		actions = append(actions, identity)
	}

	actions = append(
		actions,
		fmt.Sprintf(
			"ADD CONSTRAINT %s PRIMARY KEY (%s)",
			quoteIdent(primaryKeyName(table)),
			quoteIdent(readxml.SnakeCase(pk.Variable)),
		),
	)

	fmt.Fprintf(
		b,
		"ALTER TABLE %s.%s\n\t%s;\n\n",
		quoteIdent(schema.Schema),
		quoteIdent(table.Name),
		strings.Join(actions, ",\n\t"),
	)
	return nil
}

func generateIndexDDL(
	b *strings.Builder,
	schema *readxml.Schema,
	table readxml.Table,
	index readxml.Index,
) error {
	columns, where, err := indexDefinition(schema, table, index)
	if err != nil {
		return err
	}

	b.WriteString("CREATE ")

	if index.Unique {
		b.WriteString("UNIQUE ")
	}

	b.WriteString("INDEX IF NOT EXISTS ")
	b.WriteString(quoteIdent(indexName(table, index)))

	b.WriteString(" ON ")
	b.WriteString(quoteIdent(schema.Schema))
	b.WriteString(".")
	b.WriteString(quoteIdent(table.Name))
	b.WriteString(" (")

	for i, column := range columns {
		if i > 0 {
			b.WriteString(", ")
		}

		b.WriteString(quoteIdent(column))
	}

	b.WriteString(")")

	if where != "" {
		b.WriteString(" WHERE ")
		b.WriteString(where)
	}

	b.WriteString(";\n")

	return nil
}

// indexDefinition 返回索引的列（snake_case）和部分索引的条件 SQL（普通索引为空）。
// 部分索引可以不写 variable，这时建在主键上：只为了按条件挑出行，索引列本身用不上。
func indexDefinition(schema *readxml.Schema, table readxml.Table, index readxml.Index) ([]string, string, error) {
	var columns []string
	for _, column := range readxml.SplitTrimSpace(index.Variable) {
		columns = append(columns, readxml.SnakeCase(column))
	}

	if index.Where == "" {
		if len(columns) == 0 {
			return nil, "", fmt.Errorf("table %s has empty index", table.Name)
		}
		return columns, "", nil
	}

	if index.Method == "" {
		return nil, "", fmt.Errorf("table %s: 部分索引（where=%q）要用 method 指定名字", table.Name, index.Where)
	}
	if table.PrimaryKey == nil {
		return nil, "", fmt.Errorf("table %s has no primary key", table.Name)
	}
	bean, err := readxml.FindBean(schema, table.Bean)
	if err != nil {
		return nil, "", err
	}
	conds, err := readxml.ParseWhere(bean, table.PrimaryKey.Variable, index.Where)
	if err != nil {
		return nil, "", fmt.Errorf("table %s: %w", table.Name, err)
	}
	if len(columns) == 0 {
		columns = []string{readxml.SnakeCase(table.PrimaryKey.Variable)}
	}
	return columns, readxml.WhereSQL(conds, quoteIdent), nil
}

// normalizePredicate 把条件 SQL 化成可比较的形式。PostgreSQL 存的是自己反解的写法：
// "x" = 0 存成 (x = 0)，-1 存成 '-1'::integer，所以去掉括号、引号和类型转换再比。
// 条件只有 bool 列和整数常量，去掉这些不会把两个不同的条件变成一样。
func normalizePredicate(s string) string {
	s = strings.NewReplacer("::integer", "", "::bigint", "", "::smallint", "", "(", "", ")", "", `"`, "", "'", "").Replace(s)
	return strings.ToLower(strings.Join(strings.Fields(s), " "))
}

func indexName(table readxml.Table, index readxml.Index) string {
	if index.Where != "" {
		return fmt.Sprintf("idx_%s_where_%s", table.Name, readxml.SnakeCase(index.Method))
	}

	var columns []string

	for _, column := range readxml.SplitTrimSpace(index.Variable) {
		columns = append(columns, readxml.SnakeCase(column))
	}

	return fmt.Sprintf("idx_%s_%s", table.Name, strings.Join(columns, "_"))
}

func primaryKeyName(table readxml.Table) string {
	return fmt.Sprintf(
		"pk_%s_%s",
		table.Name,
		readxml.SnakeCase(table.PrimaryKey.Variable),
	)
}

func generateAlterDDL(b *strings.Builder, schema *readxml.Schema, table readxml.Table, dbTable *DBTable) error {
	bean, err := readxml.FindBean(schema, table.Bean)
	if err != nil {
		return err
	}

	// ------------------------------------------------------------
	// columns
	// ------------------------------------------------------------

	var addColumns []string

	for _, variable := range bean.Variables {
		columnName := readxml.SnakeCase(variable.Name)

		existing, exists := dbTable.Columns[columnName]
		if !exists {
			columnType, defaultValue, err := sqlType(variable.Type)
			if err != nil {
				return err
			}

			addColumns = append(
				addColumns,
				fmt.Sprintf(
					"ADD COLUMN %s %s NOT NULL DEFAULT %s",
					quoteIdent(columnName),
					columnType,
					defaultValue,
				),
			)

			continue
		}

		// 已存在字段只校验，不自动改类型。
		expectedType, _, err := sqlType(variable.Type)
		if err != nil {
			return err
		}

		if normalizeDBType(existing.DataType) != normalizeDBType(expectedType) {
			return fmt.Errorf("table %s column %s type mismatch: db=%s xml=%s", table.Name, columnName, existing.DataType, expectedType)
		}

		if existing.IsNullable {
			return fmt.Errorf("table %s column %s is nullable, XML requires NOT NULL", table.Name, columnName)
		}
	}

	if len(addColumns) > 0 {
		fmt.Fprintf(
			b,
			"ALTER TABLE %s.%s\n\t%s;\n\n",
			quoteIdent(schema.Schema),
			quoteIdent(table.Name),
			strings.Join(addColumns, ",\n\t"),
		)
	}

	// ------------------------------------------------------------
	// primary key / identity
	// ------------------------------------------------------------

	if table.PrimaryKey != nil {
		if dbTable.PrimaryKey == nil {
			if err := generatePrimaryKeyDDL(b, schema, table); err != nil {
				return err
			}
		} else {
			if dbTable.PrimaryKey.Name != primaryKeyName(table) {
				return fmt.Errorf("table %s primary key name mismatch: db=%s xml=%s", table.Name, dbTable.PrimaryKey.Name, primaryKeyName(table))
			}

			expected := []string{readxml.SnakeCase(table.PrimaryKey.Variable)}

			if !sameStrings(dbTable.PrimaryKey.Columns, expected) {
				return fmt.Errorf("table %s primary key columns mismatch", table.Name)
			}
		}

		if table.PrimaryKey.AutoIncrement {
			columnName := readxml.SnakeCase(table.PrimaryKey.Variable)

			column := dbTable.Columns[columnName]

			if !column.IsIdentity {
				options, err := identityOptions(table.PrimaryKey.Start, table.PrimaryKey.Step)
				if err != nil {
					return fmt.Errorf("table %s primary key: %w", table.Name, err)
				}

				identity := "ALTER COLUMN " + quoteIdent(columnName) +
					" ADD GENERATED ALWAYS AS IDENTITY" + options

				fmt.Fprintf(
					b,
					"ALTER TABLE %s.%s\n\t%s;\n\n",
					quoteIdent(schema.Schema),
					quoteIdent(table.Name),
					identity,
				)
			}
		}
	}

	// ------------------------------------------------------------
	// indexes
	// ------------------------------------------------------------

	for _, index := range table.Indexes {
		existing, exists := dbTable.Indexes[indexName(table, index)]

		if !exists {
			if err := generateIndexDDL(b, schema, table, index); err != nil {
				return err
			}

			b.WriteString("\n")
			continue
		}

		expectedColumns, expectedWhere, err := indexDefinition(schema, table, index)
		if err != nil {
			return err
		}

		if existing.Unique != index.Unique || !sameStrings(existing.Columns, expectedColumns) ||
			normalizePredicate(existing.Where) != normalizePredicate(expectedWhere) {
			return fmt.Errorf("table %s index %s definition mismatch", table.Name, indexName(table, index))
		}
	}

	return nil
}

// identityOptions 生成 ADD GENERATED ALWAYS AS IDENTITY 后面的选项。
// step <= 1 时省略 INCREMENT BY（PostgreSQL 默认就是 1）。
func identityOptions(start, step int64) (string, error) {
	if step < 0 {
		return "", fmt.Errorf("step must be >= 0")
	}

	var parts []string
	if start != 0 {
		parts = append(parts, fmt.Sprintf("START WITH %d", start))
	}
	if step > 1 {
		parts = append(parts, fmt.Sprintf("INCREMENT BY %d", step))
	}
	if len(parts) == 0 {
		return "", nil
	}
	return " (" + strings.Join(parts, " ") + ")", nil
}

func sqlType(goType string) (columnType string, defaultValue string, err error) {
	switch goType {
	case "int64":
		return "BIGINT", "0", nil

	case "int32":
		return "INTEGER", "0", nil

	case "int16":
		return "SMALLINT", "0", nil

	case "int8":
		return "SMALLINT", "0", nil

	case "string":
		return "TEXT", "''", nil

	case "bool":
		return "BOOLEAN", "false", nil

	case "float32":
		return "REAL", "0", nil

	case "float64":
		return "DOUBLE PRECISION", "0", nil

	default:
		return "", "", fmt.Errorf("unsupported Go type %q", goType)
	}
}

func quoteIdent(s string) string {
	return `"` + strings.ReplaceAll(s, `"`, `""`) + `"`
}

func normalizeDBType(s string) string {
	return strings.ToLower(strings.TrimSpace(s))
}

func sameStrings(a, b []string) bool {
	if len(a) != len(b) {
		return false
	}

	for i := range a {
		if a[i] != b[i] {
			return false
		}
	}

	return true
}
