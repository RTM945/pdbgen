// genbeans 读 pdb.xml，给每张表生成 <genOutput>/<表名>.pdb.go。genOutput 是相对路径时相对 pdb.xml
// 所在的目录，所以在哪个目录下运行都一样：
//
//	go run pdbgen/gen/bean -schema path/to/pdb.xml
//
// 输出目录里不再需要的生成文件（第一行是生成标记的）会被删掉，手写的文件不碰；内容没变的文件不重写。
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"go/token"
	"io"
	"os"
	"path"
	"path/filepath"
	"reflect"
	"strconv"
	"strings"
	"text/template"

	"pdbgen/readxml"
)

func main() {
	schemaFile := flag.String("schema", "./pdb.xml", "pdb.xml 的路径")
	flag.Parse()

	if err := run(*schemaFile, os.Stdout); err != nil {
		fmt.Fprintln(os.Stderr, "genbeans:", err)
		os.Exit(1)
	}
}

func run(schemaFile string, log io.Writer) error {
	schema, err := readxml.LoadSchema(schemaFile)
	if err != nil {
		return err
	}
	files, err := generateAll(schema)
	if err != nil {
		return err
	}
	return writeFiles(outputDir(schemaFile, schema.GenOutput), files, log)
}

// outputDir 是生成代码的目录：genOutput 是相对路径时相对 pdb.xml 所在的目录。
func outputDir(schemaFile, genOutput string) string {
	if filepath.IsAbs(genOutput) {
		return genOutput
	}
	return filepath.Join(filepath.Dir(schemaFile), genOutput)
}

// header 是生成文件的第一行。清理过期文件时只删第一行是它的文件。
const header = "// Code generated by pdbgen; DO NOT EDIT."

// fileName 是表的生成文件名。后缀不是 .go 而是 .pdb.go：表名以 _test 结尾时，文件也不会被当成测试文件。
func fileName(table string) string { return table + ".pdb.go" }

// dbctxImport 是生成代码导入的 dbctx 包。它和 readxml 在同一个模块里，从 readxml 的导入路径推出来，
// 模块改名时不用改模板。
var dbctxImport = path.Join(path.Dir(reflect.TypeFor[readxml.Schema]().PkgPath()), "dbctx")

// at 是错误信息开头的位置：pdb.xml:12:。schema 不是从文件读的（测试里拼的）时为空。
func at(schema *readxml.Schema, line int) string {
	if schema.File == "" {
		return ""
	}
	return fmt.Sprintf("%s:%d: ", schema.File, line)
}

// generateAll 生成每张表的代码：文件名 → 内容。所有问题一次报出来，带 pdb.xml 的行号。
func generateAll(schema *readxml.Schema) (map[string][]byte, error) {
	errs := checkTables(schema)
	files := make(map[string][]byte, len(schema.Tables))
	tables := make(map[string]readxml.Table, len(schema.Tables)) // 文件名 → 表，报重名用
	for _, table := range schema.Tables {
		data, err := generateTable(schema, table)
		if err != nil {
			errs = append(errs, err.Error())
			continue
		}
		name := fileName(table.Name)
		files[name], tables[name] = data, table
	}
	if len(errs) == 0 {
		errs = checkDeclarations(schema, files, tables)
	}
	if len(errs) > 0 {
		return nil, errors.New(strings.Join(errs, "\n"))
	}
	return files, nil
}

// field 是 bean 里的一列。
type field struct {
	Name         string // Go 字段名，也是查询方法的参数名
	MethodName   string
	Column       string // 已加引号、已转义成 Go 字符串内容的列名：\"act_id\"
	GoType       string
	IsPrimaryKey bool
}

// queryMethod 是按主键或索引生成的一组查询方法。
type queryMethod struct {
	Suffix       string // 方法名去掉 Get / Select / List / SelectList：普通索引是 By<列名>，部分索引是 method
	Func         string // 内部查询函数名：普通索引 query<列名>，部分索引 queryWhere<method>
	Params       string // uid int64, actId int32；没有 variable 的部分索引为空
	Args         string // uid, actId
	Where        string
	Columns      string // 条件里可更新列的 dirty 位，给 CheckPredicate；只有主键时为空
	IsList       bool
	IsPrimaryKey bool
}

type tableGen struct {
	Package       string
	DBCtx         string // dbctx 的导入路径
	TypeName      string
	ReceiverName  string
	TableAccessor string
	TableName     string // 身份表、日志、错误信息里的表名
	SQLTable      string // SQL 里的表名，带 schema、已加引号、已转义：\"public\".\"user_mail\"

	Fields       []field
	UpdateFields []field // 除主键外的列，与 dirty 位一一对应
	PK           field
	Lock         *field // pdb.xml 的 lock 列：行的修改要持有 key 等于它的 bigint 咨询锁；nil 表示不检查

	SelectColumns string
	InsertColumns string
	InsertValues  string

	QueryMethods []queryMethod
}

var tpl = template.Must(template.New("table").Parse(sourceTemplate))

func generateTable(schema *readxml.Schema, table readxml.Table) ([]byte, error) {
	gen, err := buildTableGen(schema, table)
	if err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	if err := tpl.Execute(&buf, gen); err != nil {
		return nil, err
	}
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("gofmt generated source for table %q: %w", table.Name, err)
	}
	return formatted, nil
}

// quoteIdent 返回嵌入 Go 字符串字面量后的 SQL 标识符：user -> \"user\"。
// 表名、列名一律加引号：user、end、order 这类保留字不加引号会直接语法错误。
func quoteIdent(s string) string {
	q := strconv.Quote(`"` + strings.ReplaceAll(s, `"`, `""`) + `"`)
	return q[1 : len(q)-1]
}

// supportedTypes 与 gen/ddl 的类型映射一致。
var supportedTypes = map[string]bool{
	"int64": true, "int32": true, "int16": true, "int8": true,
	"string": true, "bool": true, "float32": true, "float64": true,
}

// reservedNames 是生成代码自己用的名字：实体的内部字段，查询方法的接收者、参数和局部变量。
var reservedNames = map[string]bool{
	"loaded": true, "deleted": true, "detached": true, "foreign": true, "dirty": true,
	"t": true, "o": true, "q": true, "ctx": true, "query": true,
}

// reservedMethods 是实体上已有的方法，列的 getter 不能和它们同名。
var reservedMethods = map[string]bool{
	"TableName": true, "Identity": true, "IsDeleted": true, "Delete": true, "Detach": true,
	"DirtyColumns": true, "FlushStmt": true, "FlushDone": true, "SnapshotState": true, "RestoreState": true,
	"LockKey": true, "MarkForeign": true,
}

func checkVariable(v readxml.Variable) string {
	switch {
	case token.IsKeyword(v.Name):
		return fmt.Sprintf("列名 %q 是 Go 关键字，换个名字（比如 typ、kind）", v.Name)
	case !token.IsIdentifier(v.Name) || v.Name[0] < 'a' || v.Name[0] > 'z':
		return fmt.Sprintf("列名 %q 必须是小写字母开头的 Go 标识符", v.Name)
	case reservedNames[v.Name] || reservedMethods[readxml.PascalCase(v.Name)]:
		return fmt.Sprintf("列名 %q 和生成代码的内部名字冲突，换个名字", v.Name)
	case !supportedTypes[v.Type]:
		return fmt.Sprintf("列 %q 的类型 %q 不支持", v.Name, v.Type)
	}
	return ""
}

// validTableName 报告表名是不是小写字母开头的 snake_case：它同时是 SQL 表名、Go 文件名和 Go 名字的一部分，
// 只用小写字母、数字和下划线，大小写不敏感的文件系统上也不会两张表写进同一个文件。
func validTableName(name string) bool {
	for i, c := range name {
		switch {
		case c >= 'a' && c <= 'z':
		case i > 0 && (c >= '0' && c <= '9' || c == '_'):
		default:
			return false
		}
	}
	return name != ""
}

// checkTables 检查跨表的约束：表名合法、不重复，生成的文件名在所有平台都会编译；一个 bean 只能映射一张表——
// 生成的类型和表一一对应，身份表按表名区分记录。
func checkTables(schema *readxml.Schema) []string {
	var errs []string
	tables := make(map[string]readxml.Table)
	types := make(map[string]readxml.Table)
	for _, t := range schema.Tables {
		if !validTableName(t.Name) {
			errs = append(errs, at(schema, t.Line)+fmt.Sprintf("table %q: 表名只能用小写字母、数字和下划线，小写字母开头", t.Name))
			continue
		}
		if other, ok := tables[t.Name]; ok {
			errs = append(errs, at(schema, t.Line)+fmt.Sprintf("table %q 重复定义（第 %d 行已经定义过）", t.Name, other.Line))
			continue
		}
		tables[t.Name] = t
		if name := fileName(t.Name); !buildsEverywhere(name) {
			errs = append(errs, at(schema, t.Line)+fmt.Sprintf(
				"table %q: 生成的文件 %s 会被 Go 当成只在部分平台编译的文件（_linux、_amd64 这类后缀），换个表名", t.Name, name))
		}
		typeName := readxml.PascalCase(t.Bean)
		if other, ok := types[typeName]; ok {
			errs = append(errs, at(schema, t.Line)+fmt.Sprintf(
				"table %q 和 %q（第 %d 行）生成同一个类型 %s：一个 bean 只能映射一张表", t.Name, other.Name, other.Line, typeName))
			continue
		}
		types[typeName] = t
	}
	return errs
}

func buildTableGen(schema *readxml.Schema, table readxml.Table) (tableGen, error) {
	var errs []string
	fail := func(line int, format string, args ...any) {
		errs = append(errs, at(schema, line)+fmt.Sprintf("table %q: ", table.Name)+fmt.Sprintf(format, args...))
	}
	result := func(gen tableGen) (tableGen, error) {
		if len(errs) > 0 {
			return gen, errors.New(strings.Join(errs, "\n"))
		}
		return gen, nil
	}

	gen := tableGen{
		Package:   schema.Package,
		DBCtx:     dbctxImport,
		TableName: table.Name,
		SQLTable:  quoteIdent(schema.Schema) + "." + quoteIdent(table.Name),
	}
	bean, err := readxml.FindBean(schema, table.Bean)
	if err != nil {
		fail(table.Line, "bean %q 没有定义", table.Bean)
		return result(gen)
	}
	pk := table.PrimaryKey
	if pk == nil {
		fail(table.Line, "没有 <primaryKey>")
		return result(gen)
	}
	gen.TypeName = readxml.PascalCase(bean.Name)
	gen.ReceiverName = readxml.LowerCamelCase(bean.Name)
	gen.TableAccessor = readxml.PascalCase(table.Name) + "Table"
	if !token.IsIdentifier(gen.TypeName) || !token.IsExported(gen.TypeName) {
		fail(bean.Line, "bean 名 %q 生成的类型名 %q 不是合法的 Go 名字", bean.Name, gen.TypeName)
		return result(gen)
	}

	fields := make(map[string]field, len(bean.Variables))
	for _, v := range bean.Variables {
		if msg := checkVariable(v); msg != "" {
			fail(v.Line, "%s", msg)
		}
		if _, ok := fields[v.Name]; ok {
			fail(v.Line, "列 %q 重复", v.Name)
			continue
		}
		f := field{
			Name:         v.Name,
			MethodName:   readxml.PascalCase(v.Name),
			Column:       quoteIdent(readxml.SnakeCase(v.Name)),
			GoType:       v.Type,
			IsPrimaryKey: v.Name == pk.Variable,
		}
		fields[v.Name] = f
		gen.Fields = append(gen.Fields, f)
		if f.IsPrimaryKey {
			gen.PK = f
		} else {
			gen.UpdateFields = append(gen.UpdateFields, f)
		}
	}

	// 身份表、Insert 回填、GetById 的缓存都按 int64 自增主键实现，其他主键一律拒绝。
	switch {
	case gen.PK.Name == "":
		fail(pk.Line, "主键 %q 不在 bean 里", pk.Variable)
		return result(gen)
	case gen.PK.GoType != "int64" || !pk.AutoIncrement:
		fail(pk.Line, "主键 %q 必须是 int64 且 autoIncrement=\"true\"", pk.Variable)
	}
	switch {
	case len(gen.UpdateFields) == 0:
		fail(bean.Line, "除主键外至少要有一列")
	case len(gen.UpdateFields) > 64:
		fail(bean.Line, "除主键外最多 64 列（dirty 是 uint64 位掩码）")
	}

	// lock 列的值是保护这一行的 bigint 咨询锁的 key（docs/design.md 2.8），所以必须是 int64。
	if table.Lock != "" {
		f, ok := fields[table.Lock]
		switch {
		case !ok:
			fail(table.Line, "lock=%q 不在 bean 里", table.Lock)
		case f.GoType != "int64":
			fail(table.Line, "lock 列 %q 是 %s，必须是 int64（它的值是 bigint 咨询锁的 key）", table.Lock, f.GoType)
		default:
			gen.Lock = &f
		}
	}

	var cols, insertCols, insertValues []string
	for _, f := range gen.Fields {
		cols = append(cols, f.Column)
	}
	for i, f := range gen.UpdateFields {
		insertCols = append(insertCols, f.Column)
		insertValues = append(insertValues, "$"+strconv.Itoa(i+1))
	}
	gen.SelectColumns = strings.Join(cols, ", ")
	gen.InsertColumns = strings.Join(insertCols, ", ")
	gen.InsertValues = strings.Join(insertValues, ", ")

	// 查询方法：主键固定生成 GetById / SelectById；unique 索引生成 GetByXxx / SelectByXxx，
	// 非 unique 索引生成 ListByXxx / SelectListByXxx；部分索引（有 where）按 method 命名：Get<method> / List<method>。
	// 同一组列加同样的条件只能有一个查询。
	pkQuery := gen.newQuery([]field{gen.PK}, nil, true, "")
	pkQuery.IsPrimaryKey = true
	gen.QueryMethods = append(gen.QueryMethods, pkQuery)
	seen := map[string]bool{pk.Variable: true}
	names := map[string]bool{pkQuery.Suffix: true}
	funcs := map[string]bool{pkQuery.Func: true}
	for _, index := range table.Indexes {
		vars := readxml.SplitTrimSpace(index.Variable)
		var conds []readxml.Condition
		switch {
		case index.Where != "":
			if conds, err = readxml.ParseWhere(bean, pk.Variable, index.Where); err != nil {
				fail(index.Line, "%v", err)
				continue
			}
			if !token.IsIdentifier(index.Method) || !token.IsExported(index.Method) {
				fail(index.Line, "部分索引（where=%q）要用 method 指定方法名，大写字母开头的 Go 标识符", index.Where)
				continue
			}
			if len(vars) == 0 && index.Unique {
				fail(index.Line, "部分索引 %s 没有 variable，不能 unique", index.Method)
				continue
			}
		case index.Method != "":
			fail(index.Line, "method=%q 只用于部分索引，要配 where", index.Method)
			continue
		case len(vars) == 0:
			fail(index.Line, "<index> 既没有 variable 也没有 where")
			continue
		}
		key := strings.Join(vars, ",")
		if conds != nil {
			key += " WHERE " + readxml.WhereSQL(conds, func(s string) string { return s })
		}
		if seen[key] {
			fail(index.Line, "索引 (%s) 和主键或另一个索引重复", key)
			continue
		}
		seen[key] = true

		indexFields := make([]field, 0, len(vars))
		used := make(map[string]bool, len(vars))
		ok := true
		for _, name := range vars {
			f, found := fields[name]
			switch {
			case !found:
				fail(index.Line, "索引 (%s) 里的列 %q 不在 bean 里", key, name)
				ok = false
			case used[name]:
				fail(index.Line, "索引 (%s) 里列 %q 重复", key, name)
				ok = false
			}
			used[name] = true
			indexFields = append(indexFields, f)
		}
		if !ok {
			continue
		}
		q := gen.newQuery(indexFields, conds, index.Unique, index.Method)
		if names[q.Suffix] || funcs[q.Func] {
			fail(index.Line, "索引 (%s) 生成的方法名 %s 和别的查询重复", key, q.Suffix)
			continue
		}
		names[q.Suffix], funcs[q.Func] = true, true
		gen.QueryMethods = append(gen.QueryMethods, q)
	}
	return result(gen)
}

// newQuery 生成一组查询。conds 是部分索引的条件：常量直接写进 SQL（不用 $n 参数），规划器才能确定查询能用部分索引；
// 条件列也进 CheckPredicate，改了还没落库就按条件查，查到的是旧数据。
func (gen *tableGen) newQuery(fields []field, conds []readxml.Condition, unique bool, method string) queryMethod {
	var name, params, args, where, columns []string
	for i, f := range fields {
		name = append(name, f.MethodName)
		params = append(params, f.Name+" "+f.GoType)
		args = append(args, f.Name)
		where = append(where, f.Column+" = $"+strconv.Itoa(i+1))
		if !f.IsPrimaryKey {
			columns = append(columns, "dirty"+gen.TypeName+f.MethodName)
		}
	}
	q := queryMethod{
		Suffix: "By" + strings.Join(name, ""),
		Func:   "query" + strings.Join(name, ""),
		Params: strings.Join(params, ", "),
		Args:   strings.Join(args, ", "),
		IsList: !unique,
	}
	if conds != nil {
		q.Suffix, q.Func = method, "queryWhere"+method
		where = append(where, readxml.WhereSQL(conds, quoteIdent))
		for _, c := range conds {
			columns = append(columns, "dirty"+gen.TypeName+readxml.PascalCase(c.Variable))
		}
	}
	q.Where = strings.Join(where, " AND ")
	q.Columns = strings.Join(columns, " | ")
	return q
}
