func generateTable(
	schema *readxml.Schema,
	table readxml.Table,
) ([]byte, error) {
	gen, err := buildTableGen(schema, table)
	if err != nil {
		return nil, err
	}

	data := readxml.TableFileGen{
		Package:  schema.Package,
		TableGen: gen,
	}

	tpl, err := template.New("generated").
		Funcs(template.FuncMap{
			"joinColumns":  readxml.JoinFieldColumns,
			"placeholders": readxml.Placeholders,
		}).
		Parse(sourceTemplate)
	if err != nil {
		return nil, err
	}

	var buf bytes.Buffer

	if err := tpl.Execute(&buf, data); err != nil {
		return nil, err
	}

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf(
			"gofmt generated source for table %q: %w",
			table.Name,
			err,
		)
	}

	return formatted, nil
}

func main() {
	schemaFile := flag.String(
		"schema",
		"./pdb.xml",
		"schema xml file",
	)

	outDir := flag.String(
		"out",
		"ptable",
		"generated output directory; default: genOutput in schema",
	)

	packageName := flag.String(
		"package",
		"ptable",
		"generated package name",
	)

	flag.Parse()

	schema, err := readxml.LoadSchema(*schemaFile)
	if err != nil {
		panic(err)
	}

	// schema 中指定了 package 时，以 schema 为准；
	// 命令行显式传入 -package 时覆盖。
	if schema.Package == "" {
		schema.Package = *packageName
	} else if *packageName != "ptable" {
		schema.Package = *packageName
	}

	if *outDir == "" {
		*outDir = "./ptable"
	}

	for _, table := range schema.Tables {
		data, err := generateTable(schema, table)
		if err != nil {
			panic(err)
		}

		filename := table.Name + ".go"
		output := filepath.Join(*outDir, filename)

		if err := os.MkdirAll(
			filepath.Dir(output),
			0o755,
		); err != nil {
			panic(err)
		}

		if err := os.WriteFile(
			output,
			data,
			0o644,
		); err != nil {
			panic(err)
		}

		fmt.Printf(
			"generated %s\n",
			output,
		)
	}

	tpl, err := template.New("const").Parse(constTemplate)
	if err != nil {
		panic(err)
	}
	var buf bytes.Buffer

	if err := tpl.Execute(&buf, nil); err != nil {
		panic(err)
	}

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		panic(err)
	}

	filename := "const.go"
	output := filepath.Join(*outDir, filename)

	if err := os.MkdirAll(
		filepath.Dir(output),
		0o755,
	); err != nil {
		panic(err)
	}

	if err := os.WriteFile(
		output,
		formatted,
		0o644,
	); err != nil {
		panic(err)
	}

	fmt.Printf(
		"generated %s\n",
		output,
	)
}
