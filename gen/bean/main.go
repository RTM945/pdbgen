func buildTableGen(schema *readxml.Schema, table readxml.Table) (readxml.TableGen, error) {
	var res readxml.TableGen
	bean, err := readxml.FindBean(schema, table.Bean)
	if err != nil {
		return res, err
	}

	if table.Name == "" {
		return res, errors.New("table name is empty")
	}

	if bean.Name == "" {
		return res, errors.New("bean name is empty")
	}

	if len(bean.Variables) == 0 {
		return res, fmt.Errorf(
			"bean %q has no variables",
			bean.Name,
		)
	}

	if table.PrimaryKey == nil {
		return res, fmt.Errorf(
			"table %q has no primaryKey",
			table.Name,
		)
	}
	res.TypeName = readxml.PascalCase(bean.Name)
	res.ReceiverName = readxml.LowerCamelCase(bean.Name)
	res.TableAccessor = readxml.PascalCase(table.Name) + "Table"
	res.TableName = table.Name
	res.ErrorName = "Err" + readxml.PascalCase(bean.Name) + "NotFound"

	fieldMap := make(map[string]readxml.Field, len(bean.Variables))

	for _, v := range bean.Variables {
		if v.Name == "" || v.Type == "" {
			return res, fmt.Errorf(
				"table %q: variable name/type cannot be empty",
				table.Name,
			)
		}

		if _, exists := fieldMap[v.Name]; exists {
			return res, fmt.Errorf(
				"table %q: duplicate variable %q",
				table.Name,
				v.Name,
			)
		}

		f := readxml.Field{
			Name:       v.Name,
			MethodName: readxml.PascalCase(v.Name),
			Column:     readxml.SnakeCase(v.Name),
			GoType:     v.Type,
		}

		fieldMap[v.Name] = f
		res.Fields = append(res.Fields, f)
	}

	pk, ok := fieldMap[table.PrimaryKey.Variable]
	if !ok {
		return res, fmt.Errorf(
			"table %q: primary key variable %q not found",
			table.Name,
			table.PrimaryKey.Variable,
		)
	}

	pk.IsPrimaryKey = true
	pk.AutoIncrement = table.PrimaryKey.AutoIncrement

	res.PK = pk
	res.AutoIncrement = pk.AutoIncrement

	for i := range res.Fields {
		if res.Fields[i].Name == pk.Name {
			res.Fields[i] = pk
		}
	}

	// INSERT:
	// auto increment PK 不需要传。
	for _, f := range res.Fields {
		if f.IsPrimaryKey && f.AutoIncrement {
			continue
		}

		res.InsertFields = append(res.InsertFields, f)
	}

	// UPDATE:
	// PK 永远不更新，其他所有字段都可以更新。
	for _, f := range res.Fields {
		if f.IsPrimaryKey {
			continue
		}

		res.UpdateFields = append(res.UpdateFields, f)
	}

	columns := make([]string, 0, len(res.Fields))

	for _, f := range res.Fields {
		columns = append(columns, f.Column)
	}

	res.SelectColumns = strings.Join(columns, ", ")

	// 主键查询
	pkMethod := "GetBy" + pk.MethodName

	res.QueryMethods = append(res.QueryMethods, readxml.QueryMethod{
		MethodName: pkMethod,
		Params:     pk.Name + " " + pk.GoType,
		Args:       pk.Name,
		Where:      pk.Column + " = $1",
	})

	seenMethods := map[string]struct{}{
		pkMethod: {},
	}

	// unique index -> GetByXXX
	for _, index := range table.Indexes {
		if !index.Unique {
			continue
		}

		varNames := readxml.SplitTrimSpace(index.Variable)

		if len(varNames) == 0 {
			return res, fmt.Errorf(
				"table %q: index %q has empty variable list",
				table.Name,
				index.Name,
			)
		}

		params := make([]string, 0, len(varNames))
		args := make([]string, 0, len(varNames))
		conditions := make([]string, 0, len(varNames))
		methodParts := make([]string, 0, len(varNames))

		for i, name := range varNames {
			f, exists := fieldMap[name]

			if !exists {
				return res, fmt.Errorf(
					"table %q: index %q references unknown variable %q",
					table.Name,
					index.Name,
					name,
				)
			}

			params = append(
				params,
				fmt.Sprintf("%s %s", f.Name, f.GoType),
			)

			args = append(args, f.Name)

			conditions = append(
				conditions,
				fmt.Sprintf("%s = $%d", f.Column, i+1),
			)

			methodParts = append(
				methodParts,
				f.MethodName,
			)
		}

		methodName := "GetBy" + strings.Join(methodParts, "")

		if _, exists := seenMethods[methodName]; exists {
			continue
		}

		seenMethods[methodName] = struct{}{}

		res.QueryMethods = append(
			res.QueryMethods,
			readxml.QueryMethod{
				MethodName: methodName,
				Params:     strings.Join(params, ", "),
				Args:       strings.Join(args, ", "),
				Where:      strings.Join(conditions, " AND "),
			},
		)
	}

	return res, nil
}

const constTemplate = `// Code generated by pdbgen; DO NOT EDIT.
package ptable

import (
	"context"

	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgconn"
)

type txKey struct{}

type DBTX interface {
	Exec(ctx context.Context, sql string, arguments ...any) (pgconn.CommandTag, error)
	Query(ctx context.Context, sql string, args ...any) (pgx.Rows, error)
	QueryRow(ctx context.Context, sql string, args ...any) pgx.Row
}

func txFromCtx(ctx context.Context) DBTX {
	return ctx.Value(txKey{}).(DBTX)
}
`

